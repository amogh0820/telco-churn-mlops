"""Write the real training results into the README.

The Results section of README.md sits between two HTML-comment markers. This
script regenerates everything between them from reports/test_report.json, so
the numbers in the README are always the numbers the last training run actually
produced -- never hand-copied, never stale, never invented.

Run:  python -m scripts.update_readme_results       (or: make report)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = PROJECT_ROOT / "reports" / "test_report.json"
README_PATH = PROJECT_ROOT / "README.md"

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"

PRETTY = {
    "logistic_regression": "Logistic regression",
    "random_forest": "Random forest",
    "hist_gradient_boosting": "Hist gradient boosting",
}


def render(report: dict) -> str:
    metrics = report["test_metrics"]
    comparison = report.get("model_comparison", {})
    winner = report["model_family"]
    threshold = report["threshold"]

    lines: list[str] = []
    lines.append(
        f"_Generated by `make report` from the run of {report.get('trained_at', 'n/a')}._"
    )
    lines.append("")

    lines.append("### Model comparison")
    lines.append("")
    lines.append("Cross-validated PR-AUC on the training split, 5 folds. The winner is")
    lines.append("chosen here, before the test set is touched.")
    lines.append("")
    lines.append("| Model | CV PR-AUC | Std | |")
    lines.append("|---|---|---|---|")
    for name, stats in comparison.items():
        mark = " **selected**" if name == winner else ""
        lines.append(
            f"| {PRETTY.get(name, name)} | {stats['cv_pr_auc']:.4f} | "
            f"±{stats['cv_pr_auc_std']:.4f} |{mark} |"
        )
    lines.append("")

    lines.append("### Held-out test performance")
    lines.append("")
    lines.append(
        f"Single evaluation of **{PRETTY.get(winner, winner)}** on the 20% test split, "
        f"at the tuned threshold of **{threshold:.2f}**."
    )
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    rows = [
        ("ROC-AUC", f"{metrics['roc_auc']:.4f}"),
        ("PR-AUC (average precision)", f"{metrics['pr_auc']:.4f}"),
        ("Brier score (lower is better)", f"{metrics['brier_score']:.4f}"),
        ("Precision", f"{metrics['precision']:.4f}"),
        ("Recall", f"{metrics['recall']:.4f}"),
        ("F1", f"{metrics['f1']:.4f}"),
        ("Accuracy", f"{metrics['accuracy']:.4f}"),
        ("Decision threshold", f"{threshold:.2f}"),
    ]
    for label, value in rows:
        lines.append(f"| {label} | {value} |")
    lines.append("")

    lines.append("Confusion matrix at that threshold:")
    lines.append("")
    lines.append("| | Predicted stay | Predicted churn |")
    lines.append("|---|---|---|")
    lines.append(
        f"| **Actually stayed** | {metrics['true_negatives']} | {metrics['false_positives']} |"
    )
    lines.append(
        f"| **Actually churned** | {metrics['false_negatives']} | {metrics['true_positives']} |"
    )
    lines.append("")

    tuned = metrics["campaign_value"]
    naive = metrics["campaign_value_at_0.5"]
    delta = tuned - naive
    lines.append("### Campaign value")
    lines.append("")
    lines.append(
        "Net value of a retention campaign on the test cohort under the cost "
        "assumptions in `src/config.py`."
    )
    lines.append("")
    lines.append("| Threshold | Net campaign value |")
    lines.append("|---|---|")
    lines.append(f"| Naive 0.50 | ${naive:,.0f} |")
    lines.append(f"| Tuned {threshold:.2f} | ${tuned:,.0f} |")
    lines.append(
        f"| **Difference** | **{'+' if delta >= 0 else '−'}${abs(delta):,.0f}** |"
    )
    lines.append("")
    cohort = (
        metrics["true_negatives"]
        + metrics["false_positives"]
        + metrics["false_negatives"]
        + metrics["true_positives"]
    )
    lines.append(
        f"On a test cohort of {cohort:,} customers. Scale to the full "
        "base to state the annual figure."
    )

    return "\n".join(lines)


def main() -> int:
    if not REPORT_PATH.exists():
        print(
            f"{REPORT_PATH} not found. Run `make data && make train` first.",
            file=sys.stderr,
        )
        return 1

    report = json.loads(REPORT_PATH.read_text())
    readme = README_PATH.read_text()

    if START not in readme or END not in readme:
        print(
            f"Could not find the {START} / {END} markers in README.md.",
            file=sys.stderr,
        )
        return 1

    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    README_PATH.write_text(f"{head}{START}\n\n{render(report)}\n\n{END}{tail}")
    print(f"Wrote results for {report['model_family']} into README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
